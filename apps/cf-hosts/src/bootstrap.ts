/**
 * The one bootstrap used by every provider.
 *
 * Contract with providers:
 *   1. Upload `bootstrap.sh` and `host.env` (mode 0600) into a staging directory the sandbox's
 *      default user can write (STAGING_DIR below, relative to that user's HOME).
 *   2. Run `bash <staging>/bootstrap.sh <staging>` detached. It re-executes itself through `sudo -n`
 *      when not root, so it works for Daytona (`daytona` user), E2B (`user`) and Cloudflare (root).
 *   3. Read state with STATUS_COMMAND and logs with logsCommand(); neither needs root.
 *
 * Secrets travel only inside host.env (uploaded as a file, never in a URL or command line), which
 * the script installs as /opt/hlhost/host.env owned by the daemon user with mode 0600 and then
 * deletes from staging. The script never enables `set -x` and never prints the env file.
 */
import type { BootstrapPhase, ProviderName } from './schemas'

export const HL_DIR = '/opt/hlhost'
export const HL_USER = 'humanlayer'
export const HL_HOME = `/home/${HL_USER}`
export const BOOTSTRAP_LOG = `${HL_DIR}/logs/bootstrap.log`
export const DAEMON_LOG = `${HL_DIR}/logs/daemon.log`
/** Staging directory name, created under the provider user's HOME. */
export const STAGING_DIR_NAME = '.hlhost-staging'

const ENV_KEY = /^[A-Z_][A-Z0-9_]*$/

/** POSIX single-quote a value so `. file` / bash sees it verbatim (newlines and quotes included). */
export function shellQuote(value: string): string {
	return `'${value.replace(/'/g, `'\\''`)}'`
}

export interface HostEnvInput {
	hostId: string
	provider: ProviderName
	daemonToken: string
	env: Record<string, string>
}

/** The full environment handed to `humanlayer daemon launch` (caller env + fixed host vars). */
export function buildHostEnv(input: HostEnvInput) {
	return {
		...input.env,
		RIPTIDE_DAEMON_TOKEN: input.daemonToken,
		HUMANLAYER_HOST_ID: input.hostId,
		HUMANLAYER_HOST_PROVIDER: input.provider,
		HUMANLAYER_DISABLE_SELF_UPDATE: '1',
	}
}

/** Render a `KEY='value'` file that bash can source with `set -a`. */
export function renderEnvFile(vars: Record<string, string>): string {
	const lines = ['# Generated by humanlayer-hosts. Contains secrets: mode 0600, never print.']
	for (const [key, value] of Object.entries(vars).sort(([a], [b]) => a.localeCompare(b))) {
		if (!ENV_KEY.test(key)) throw new Error(`invalid env key: ${key}`)
		if (value.includes('\0')) throw new Error(`env value for ${key} contains NUL`)
		lines.push(`${key}=${shellQuote(value)}`)
	}
	return `${lines.join('\n')}\n`
}

export interface BootstrapParams {
	hostId: string
	provider: ProviderName
	/** Public URL of the linux-x64 binary (served by this Worker under /cli/...). */
	cliUrl: string
	/** Expected sha256 of the binary; the script refuses a mismatching download. */
	cliSha256: string | null
	cliVersion: string | null
}

const SAFE_URL = /^https:\/\/[A-Za-z0-9.-]+(:\d+)?\/[A-Za-z0-9._~\/-]*$/

export function renderBootstrapScript(p: BootstrapParams): string {
	// Everything interpolated below is validated so the script never needs runtime quoting tricks.
	if (!SAFE_URL.test(p.cliUrl)) throw new Error(`unsafe cliUrl: ${p.cliUrl}`)
	if (p.cliSha256 !== null && !/^[0-9a-f]{64}$/.test(p.cliSha256)) throw new Error('cliSha256 must be hex sha256')
	if (!/^[0-9a-f-]{36}$/.test(p.hostId)) throw new Error('hostId must be a UUID')
	if (p.cliVersion !== null && !/^[A-Za-z0-9._-]+$/.test(p.cliVersion)) throw new Error('bad cliVersion')

	return `#!/usr/bin/env bash
# HumanLayer cloud host bootstrap. Generated by humanlayer-hosts; idempotent; safe to re-run.
# Usage: bash bootstrap.sh <staging-dir>
# Never enable shell tracing here: host.env holds secrets.
set -uo pipefail

HL_STAGING="\${1:-}"
HL_DIR=${HL_DIR}
HL_USER=${HL_USER}
HL_HOME=${HL_HOME}
HL_HOST_ID=${p.hostId}
HL_PROVIDER=${p.provider}
HL_CLI_URL=${shellQuote(p.cliUrl)}
HL_CLI_SHA256=${p.cliSha256 ?? ''}
HL_CLI_VERSION=${p.cliVersion ?? 'unknown'}

if [ "$(id -u)" -ne 0 ]; then
	if command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
		exec sudo -n bash "$0" "$@"
	fi
	echo "hlhost bootstrap needs root or passwordless sudo" >&2
	exit 1
fi

# sudo keeps the caller's cwd (e.g. /home/daytona), which the daemon user cannot read.
cd /
mkdir -p "$HL_DIR/logs" "$HL_DIR/run"
chmod 755 "$HL_DIR" "$HL_DIR/logs"
touch "$HL_DIR/logs/bootstrap.log"
chmod 644 "$HL_DIR/logs/bootstrap.log"
exec >>"$HL_DIR/logs/bootstrap.log" 2>&1

log() { echo "[hlhost $(date -u +%Y-%m-%dT%H:%M:%SZ)] $*"; }
phase() { echo "$1" >"$HL_DIR/phase"; chmod 644 "$HL_DIR/phase"; log "phase=$1"; }
fail() { echo "$*" >"$HL_DIR/error"; chmod 644 "$HL_DIR/error"; phase failed; log "ERROR: $*"; exit 1; }

if command -v flock >/dev/null 2>&1; then
	exec 9>"$HL_DIR/run/bootstrap.lock"
	if ! flock -w 600 9; then fail "another bootstrap held the lock for 10 minutes"; fi
fi

rm -f "$HL_DIR/error"
phase starting
log "host=$HL_HOST_ID provider=$HL_PROVIDER cli_version=$HL_CLI_VERSION uid=$(id -u) os=$(. /etc/os-release 2>/dev/null; echo "\${PRETTY_NAME:-unknown}")"

# ---------------------------------------------------------------- packages
phase packages
missing=""
command -v git >/dev/null 2>&1 || missing="$missing git"
command -v ps >/dev/null 2>&1 || missing="$missing procps"
command -v pgrep >/dev/null 2>&1 || missing="$missing procps"
command -v curl >/dev/null 2>&1 || missing="$missing curl"
command -v runuser >/dev/null 2>&1 || missing="$missing util-linux"
command -v useradd >/dev/null 2>&1 || missing="$missing passwd"
command -v setsid >/dev/null 2>&1 || missing="$missing util-linux"
[ -s /etc/ssl/certs/ca-certificates.crt ] || missing="$missing ca-certificates"
if [ -n "$missing" ]; then
	command -v apt-get >/dev/null 2>&1 || fail "missing packages ($missing) and no apt-get (glibc Debian/Ubuntu image required)"
	export DEBIAN_FRONTEND=noninteractive
	ok=0
	for attempt in 1 2 3; do
		if apt-get update -qq && apt-get install -y -qq --no-install-recommends $missing ca-certificates; then ok=1; break; fi
		log "apt-get attempt $attempt failed; retrying"
		sleep $((attempt * 5))
	done
	[ "$ok" = 1 ] || fail "apt-get install failed for:$missing"
fi
log "git: $(git --version 2>&1)"

# ---------------------------------------------------------------- user
phase user
if ! id -u "$HL_USER" >/dev/null 2>&1; then
	useradd --create-home --home-dir "$HL_HOME" --shell /bin/bash "$HL_USER" || fail "useradd failed"
fi
mkdir -p "$HL_HOME/.local/bin" "$HL_HOME/.humanlayer/riptide"
echo "$HL_HOST_ID" >"$HL_HOME/.humanlayer/riptide/host_id"
chown -R "$HL_USER:$HL_USER" "$HL_HOME/.local" "$HL_HOME/.humanlayer"
chown "$HL_USER:$HL_USER" "$HL_DIR/logs" "$HL_DIR/run"

as_user() { runuser -u "$HL_USER" -- env -i HOME="$HL_HOME" USER="$HL_USER" PATH="$HL_HOME/.local/bin:/usr/local/bin:/usr/bin:/bin" "$@"; }

# Install the env file handed over by the provider (0600, owned by the daemon user).
env_changed=0
if [ -n "$HL_STAGING" ] && [ -f "$HL_STAGING/host.env" ]; then
	install -m 600 -o "$HL_USER" -g "$HL_USER" "$HL_STAGING/host.env" "$HL_DIR/host.env.new"
	rm -f "$HL_STAGING/host.env"
	if ! cmp -s "$HL_DIR/host.env.new" "$HL_DIR/host.env" 2>/dev/null; then env_changed=1; fi
	mv -f "$HL_DIR/host.env.new" "$HL_DIR/host.env"
fi
[ -f "$HL_DIR/host.env" ] || fail "no host.env was provided"
if [ -n "$HL_STAGING" ] && [ -f "$HL_STAGING/bootstrap.sh" ] && [ "$HL_STAGING/bootstrap.sh" != "$HL_DIR/bootstrap.sh" ]; then
	install -m 755 "$HL_STAGING/bootstrap.sh" "$HL_DIR/bootstrap.sh"
fi
has_env() { grep -q "^$1=" "$HL_DIR/host.env"; }

# ---------------------------------------------------------------- humanlayer CLI
phase cli
current_sha=""
[ -x /usr/local/bin/humanlayer ] && current_sha="$(sha256sum /usr/local/bin/humanlayer | cut -d' ' -f1)"
if [ -z "$current_sha" ] || { [ -n "$HL_CLI_SHA256" ] && [ "$current_sha" != "$HL_CLI_SHA256" ]; }; then
	tmp="$(mktemp /tmp/humanlayer.XXXXXX)"
	curl -fsSL --retry 5 --retry-delay 3 --connect-timeout 20 -o "$tmp" "$HL_CLI_URL" || fail "download of humanlayer CLI failed"
	got="$(sha256sum "$tmp" | cut -d' ' -f1)"
	if [ -n "$HL_CLI_SHA256" ] && [ "$got" != "$HL_CLI_SHA256" ]; then
		rm -f "$tmp"
		fail "humanlayer CLI sha256 mismatch (got $got)"
	fi
	install -m 755 "$tmp" /usr/local/bin/humanlayer
	rm -f "$tmp"
	log "installed humanlayer CLI sha256=$got"
else
	log "humanlayer CLI already installed sha256=$current_sha"
fi
log "humanlayer --version: $(as_user /usr/local/bin/humanlayer --version 2>&1 | tail -n 1)"

# ---------------------------------------------------------------- Claude Code
phase claude
if [ ! -x "$HL_HOME/.local/bin/claude" ]; then
	ok=0
	for attempt in 1 2 3; do
		if as_user bash -c 'curl -fsSL https://claude.ai/install.sh | bash' >>"$HL_DIR/logs/bootstrap.log" 2>&1; then ok=1; break; fi
		log "Claude Code install attempt $attempt failed; retrying"
		sleep $((attempt * 5))
	done
	[ "$ok" = 1 ] && [ -x "$HL_HOME/.local/bin/claude" ] || fail "Claude Code install failed"
fi
log "claude --version: $(as_user "$HL_HOME/.local/bin/claude" --version 2>&1 | tail -n 1)"

# ---------------------------------------------------------------- git + GitHub
phase git
as_user git config --global init.defaultBranch main
as_user git config --global user.name >/dev/null 2>&1 || as_user git config --global user.name "HumanLayer Cloud Host"
as_user git config --global user.email >/dev/null 2>&1 || as_user git config --global user.email "cloud-host@humanlayer.local"
as_user git config --global --unset-all credential.https://github.com.helper >/dev/null 2>&1 || true
if has_env GH_TOKEN; then
	# The helper reads GH_TOKEN from the daemon's environment at call time; the token itself is never
	# written to git config or ~/.git-credentials.
	as_user git config --global credential.https://github.com.helper ''
	as_user git config --global --add credential.https://github.com.helper '!f() { test "$1" = get || exit 0; echo username=x-access-token; echo "password=$GH_TOKEN"; }; f'
	if ! command -v gh >/dev/null 2>&1 && command -v apt-get >/dev/null 2>&1; then
		DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends gh >/dev/null 2>&1 || log "gh not installed (optional)"
	fi
	log "git credential helper configured for github.com (token from env); gh: $(command -v gh >/dev/null 2>&1 && gh --version | head -n 1 || echo absent)"
else
	log "no GH_TOKEN supplied; private GitHub repos will not be reachable"
fi

# ---------------------------------------------------------------- daemon supervisor
phase daemon
cat >"$HL_DIR/run-daemon.sh" <<'SUPERVISOR'
#!/usr/bin/env bash
# Restarts \`humanlayer daemon launch\` forever, with capped exponential backoff.
set -u
echo $$ >/opt/hlhost/run/supervisor.pid
set -a
. /opt/hlhost/host.env
set +a
export HOME=/home/humanlayer USER=humanlayer SHELL=/bin/bash
export PATH=/home/humanlayer/.local/bin:/usr/local/bin:/usr/bin:/bin
export HUMANLAYER_DISABLE_SELF_UPDATE=1 IS_SANDBOX=1 DISABLE_AUTOUPDATER=1
export HUMANLAYER_CLAUDE_PATH=/home/humanlayer/.local/bin/claude
export LOG_LEVEL="\${LOG_LEVEL:-info}"
LOG=/opt/hlhost/logs/daemon.log
backoff=2
cd "$HOME"
while true; do
	if [ -f "$LOG" ] && [ "$(stat -c %s "$LOG" 2>/dev/null || echo 0)" -gt 52428800 ]; then mv -f "$LOG" "$LOG.1"; fi
	echo "[supervisor $(date -u +%Y-%m-%dT%H:%M:%SZ)] starting: humanlayer daemon launch" >>"$LOG"
	started=$(date +%s)
	/usr/local/bin/humanlayer daemon launch >>"$LOG" 2>&1 </dev/null
	code=$?
	if [ $(( $(date +%s) - started )) -ge 120 ]; then backoff=2; else backoff=$(( backoff * 2 )); [ "$backoff" -gt 60 ] && backoff=60; fi
	echo "[supervisor $(date -u +%Y-%m-%dT%H:%M:%SZ)] daemon exited code=$code; restarting in \${backoff}s" >>"$LOG"
	sleep "$backoff"
done
SUPERVISOR
chmod 755 "$HL_DIR/run-daemon.sh"
touch "$HL_DIR/logs/daemon.log"
chown "$HL_USER:$HL_USER" "$HL_DIR/logs/daemon.log"
chmod 644 "$HL_DIR/logs/daemon.log"

supervisor_pid="$(cat "$HL_DIR/run/supervisor.pid" 2>/dev/null || true)"
supervisor_alive=0
if [ -n "$supervisor_pid" ] && kill -0 "$supervisor_pid" 2>/dev/null; then supervisor_alive=1; fi
if [ "$supervisor_alive" = 1 ] && [ "$env_changed" = 1 ]; then
	log "credentials changed; restarting daemon supervisor (pgid $supervisor_pid)"
	kill -TERM -- "-$supervisor_pid" 2>/dev/null || kill -TERM "$supervisor_pid" 2>/dev/null || true
	sleep 3
	kill -KILL -- "-$supervisor_pid" 2>/dev/null || true
	pkill -KILL -u "$HL_USER" -f '[h]umanlayer daemon launch' 2>/dev/null || true
	supervisor_alive=0
fi
if [ "$supervisor_alive" = 0 ]; then
	# 9>&- : do not leak the bootstrap lock into the long-lived supervisor.
	runuser -u "$HL_USER" -- setsid nohup "$HL_DIR/run-daemon.sh" >/dev/null 2>&1 </dev/null 9>&- &
	disown || true
	log "started daemon supervisor"
else
	log "daemon supervisor already running (pid $supervisor_pid)"
fi

for i in $(seq 1 30); do
	if pgrep -u "$HL_USER" -f '[h]umanlayer daemon launch' >/dev/null 2>&1; then
		log "daemon process is running (pid $(pgrep -u "$HL_USER" -f '[h]umanlayer daemon launch' | head -n 1))"
		phase running
		exit 0
	fi
	sleep 1
done
fail "daemon process did not start within 30s (see daemon.log)"
`
}

/**
 * Prints `key=value` lines; needs no root. The `[h]` bracket trick keeps pgrep from matching the
 * shell that runs this very command line.
 */
export const STATUS_COMMAND = [
	`echo "phase=$(cat ${HL_DIR}/phase 2>/dev/null || echo none)"`,
	`if pgrep -f '[r]un-daemon.sh' >/dev/null 2>&1; then echo supervisor=1; else echo supervisor=0; fi`,
	`if pgrep -f '[h]umanlayer daemon launch' >/dev/null 2>&1; then echo daemon=1; else echo daemon=0; fi`,
	`echo "error=$(head -c 500 ${HL_DIR}/error 2>/dev/null | tr '\\n' ' ')"`,
].join('; ')

export function logsCommand(lines: number): string {
	const n = Math.max(1, Math.min(2000, Math.floor(lines)))
	return [
		`echo '=====HLHOST:bootstrap====='`,
		`tail -n ${n} ${BOOTSTRAP_LOG} 2>/dev/null`,
		`echo '=====HLHOST:daemon====='`,
		`tail -n ${n} ${DAEMON_LOG} 2>/dev/null`,
		`true`,
	].join('; ')
}

export interface ParsedStatus {
	phase: BootstrapPhase
	supervisorRunning: boolean
	daemonRunning: boolean
	error: string | null
}

const PHASES: ReadonlySet<string> = new Set([
	'none',
	'starting',
	'packages',
	'user',
	'cli',
	'claude',
	'git',
	'daemon',
	'running',
	'failed',
])

export function parseStatusOutput(out: string): ParsedStatus {
	const kv = new Map<string, string>()
	for (const line of out.split('\n')) {
		const i = line.indexOf('=')
		if (i > 0) kv.set(line.slice(0, i).trim(), line.slice(i + 1).trim())
	}
	const phase = kv.get('phase') ?? 'none'
	const error = kv.get('error') ?? ''
	return {
		phase: (PHASES.has(phase) ? phase : 'none') as BootstrapPhase,
		supervisorRunning: kv.get('supervisor') === '1',
		daemonRunning: kv.get('daemon') === '1',
		error: error.length > 0 ? error : null,
	}
}

export function parseLogsOutput(out: string): { bootstrap: string; daemon: string } {
	const b = out.indexOf('=====HLHOST:bootstrap=====')
	const d = out.indexOf('=====HLHOST:daemon=====')
	if (b < 0 || d < 0) return { bootstrap: out, daemon: '' }
	return {
		bootstrap: out.slice(b + '=====HLHOST:bootstrap====='.length, d).replace(/^\n/, ''),
		daemon: out.slice(d + '=====HLHOST:daemon====='.length).replace(/^\n/, ''),
	}
}

/** Map bootstrap status onto the normalised host state, given the sandbox is up. */
export function stateFromStatus(s: ParsedStatus): 'bootstrapping' | 'running' | 'degraded' | 'failed' {
	if (s.phase === 'failed') return 'failed'
	if (s.phase === 'running') return s.daemonRunning ? 'running' : 'degraded'
	return 'bootstrapping'
}
