/**
 * Builds Workers Static Assets `_headers` files that recreate the response headers the AWS
 * reference sets with a CloudFront response headers policy
 * (packages/pulumi-helpers/src/cloudfront.ts, createSpaSecurityHeadersPolicy).
 *
 * The CSP stays report-only, as upstream ships it. S3 origins are replaced by R2 (artifacts live in
 * the `human-flare-artifacts` bucket here); Sentry is not configured, so no ingest origin.
 */

const PERMISSIONS_POLICY = [
	'camera=()',
	'microphone=()',
	'geolocation=()',
	'payment=()',
	'usb=()',
	'serial=()',
	'hid=()',
	'bluetooth=()',
	'accelerometer=()',
	'gyroscope=()',
	'magnetometer=()',
	'display-capture=()',
	'xr-spatial-tracking=()',
	'fullscreen=(self)',
	'autoplay=(self)',
	'clipboard-read=(self)',
	'clipboard-write=(self)',
	'publickey-credentials-get=(self)',
].join(', ')

const WORKOS_ORIGINS = ['https://api.workos.com', 'https://*.authkit.app']
const ARTIFACT_ORIGINS = ['https://*.r2.cloudflarestorage.com']

export type SpaHeaderOptions = {
	apiOrigin: string
	syncOrigin: string
	additionalConnectSrc?: string[]
}

export function spaContentSecurityPolicy(options: SpaHeaderOptions): string {
	return [
		"default-src 'self'",
		"script-src 'self'",
		"style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
		"font-src 'self' data: https://fonts.gstatic.com",
		"img-src 'self' data: blob: https:",
		[
			"connect-src 'self'",
			options.apiOrigin,
			options.syncOrigin,
			...WORKOS_ORIGINS,
			...ARTIFACT_ORIGINS,
			...(options.additionalConnectSrc ?? []),
		].join(' '),
		["frame-src 'self' blob:", ...ARTIFACT_ORIGINS].join(' '),
		"worker-src 'self' blob:",
		"media-src 'self' data: blob:",
		"object-src 'none'",
		"base-uri 'self'",
		["form-action 'self'", ...WORKOS_ORIGINS].join(' '),
		"frame-ancestors 'self'",
		'upgrade-insecure-requests',
	]
		.map((directive) => `${directive};`)
		.join(' ')
}

function securityHeaders(): string[] {
	return [
		'X-Content-Type-Options: nosniff',
		'X-Frame-Options: SAMEORIGIN',
		'Referrer-Policy: strict-origin-when-cross-origin',
		'Strict-Transport-Security: max-age=63072000; includeSubDomains; preload',
		`Permissions-Policy: ${PERMISSIONS_POLICY}`,
	]
}

function block(path: string, headers: string[]): string {
	return [path, ...headers.map((header) => `  ${header}`)].join('\n')
}

/** `_headers` for the Vite SPAs (riptide-ui, riptide-cloud). */
export function spaHeadersFile(options: SpaHeaderOptions): string {
	return [
		'# Generated by scripts/cloudflare/deploy.ts. Do not edit; edit scripts/cloudflare/headers.ts.',
		block('/*', [
			...securityHeaders(),
			`Content-Security-Policy-Report-Only: ${spaContentSecurityPolicy(options)}`,
		]),
		// Vite fingerprints everything under /assets/: cache forever.
		block('/assets/*', ['Cache-Control: public, max-age=31536000, immutable']),
		'',
	].join('\n\n')
}

/** `_headers` for the VitePress docs site. */
export function docsHeadersFile(): string {
	return [
		'# Generated by scripts/cloudflare/deploy.ts. Do not edit; edit scripts/cloudflare/headers.ts.',
		block('/*', securityHeaders()),
		block('/assets/*', ['Cache-Control: public, max-age=31536000, immutable']),
		'',
	].join('\n\n')
}
